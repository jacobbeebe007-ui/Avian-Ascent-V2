#!/usr/bin/env node
/* Generate js/data/bird-card-passive-scaling.js from bird-passives.js */
import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const passivesPath = path.join(ROOT, 'js', 'data', 'combat-pack', 'bird-passives.js');
const outPath = path.join(ROOT, 'js', 'data', 'bird-card-passive-scaling.js');

const code = readFileSync(passivesPath, 'utf8');
const sandbox = { console, globalThis: null };
sandbox.globalThis = sandbox;
vm.createContext(sandbox);
vm.runInContext(code, sandbox, { filename: 'bird-passives.js' });

const passives = sandbox.Avian?.data?.combatPack?.birdPassives || {};
const scaling = {};

for (const [id, p] of Object.entries(passives)) {
  const key = p.birdKey;
  if (!key) continue;
  const effect = String(p.effect || '');
  const m = effect.match(/\+?(\d+(?:\.\d+)?)\s*%/);
  const grey = m ? Number(m[1]) / 100 : 0.08;
  const step = 0.02;
  scaling[key] = {
    passiveId: id,
    scaling: 'percentBonus',
    grey: grey,
    green: grey + step,
    blue: grey + step * 2,
    purple: grey + step * 3,
    gold: grey + step * 4,
    orange: grey + step * 4,
    effectTemplate: effect.replace(/\+?(\d+(?:\.\d+)?)\s*%/, '+{pct}%'),
  };
}

const body = `/* GENERATED by scripts/generate-bird-card-passive-scaling.mjs — do not edit by hand. */
(function () {
  'use strict';
  var Avian = globalThis.Avian || (globalThis.Avian = {});
  Avian.data = Avian.data || Object.create(null);
  Avian.data.birdCardPassiveScaling = Object.freeze(${JSON.stringify(scaling, null, 2)});
})();
`;

writeFileSync(outPath, body, 'utf8');
console.log('[generate] wrote', outPath, 'entries:', Object.keys(scaling).length);
