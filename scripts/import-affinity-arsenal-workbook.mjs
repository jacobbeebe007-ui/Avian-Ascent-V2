#!/usr/bin/env node
/*
 * Affinity Arsenal v0.6 importer entry point.
 *
 * Regenerates inert data packs from either:
 *   AA_V06_DUMP_DIR=/tmp/aa_wb_v06  (JSON sheet dumps), or
 *   AA_AFFINITY_ARSENAL_WORKBOOK=/path/to/v0.6.xlsx
 *
 * Canonical outputs only (no -v2 siblings):
 *   aspects, affinities, effect-tiers, ailment-families, orb-focuses,
 *   combinations, weapon-access, progression/*, enemy-scaling-profiles,
 *   display-glossary.
 *
 * Skills/families/items receive v0.6 overlays (COMBO_* merge, EN roles,
 * Dagger Pinion rename, Greatbow locks, orbFocus stamps).
 *
 * combat-config.js remains hand-authored; this script verifies it matches
 * the expected packVersion after import.
 *
 * Usage:
 *   AA_V06_DUMP_DIR=/tmp/aa_wb_v06 node scripts/import-affinity-arsenal-workbook.mjs
 */
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { spawnSync } from 'node:child_process';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const DUMP = process.env.AA_V06_DUMP_DIR
  || (existsSync('/tmp/aa_wb_v06') ? '/tmp/aa_wb_v06' : null);
const WORKBOOK = process.env.AA_AFFINITY_ARSENAL_WORKBOOK
  || path.join(process.env.HOME || '', 'Documents', 'Avian Ascent', 'Avian Workbooks',
    'Newest Avian_Ascent_Master_Affinity_Ailments_and_Arsenal_v0.6.xlsx');

function fail(msg) {
  console.error('import-affinity-arsenal: ' + msg);
  process.exit(1);
}

if (!DUMP || !existsSync(DUMP)) {
  fail('Set AA_V06_DUMP_DIR to a directory of sheet JSON dumps (see /tmp/aa_wb_v06). '
    + 'XLSX parse path: place workbook at AA_AFFINITY_ARSENAL_WORKBOOK and dump sheets first.');
}

const required = [
  'Affinities_and_Ailments.json',
  'Ailment_Arsenal.json',
  'Combination_Techniques.json',
  'Effect_Tiers.json',
  'Progression_Data.json',
  'Progression_Rules.json',
  'Enemy_Scaling.json',
  'Recovery_and_Defence.json',
];
for (const f of required) {
  if (!existsSync(path.join(DUMP, f))) fail('missing dump sheet ' + f);
}

console.log('Affinity Arsenal v0.6 importer');
console.log('  dump:', DUMP);
console.log('  workbook (reference):', existsSync(WORKBOOK) ? WORKBOOK : '(not present)');

/* Re-run the generation helper embedded as Python for reliability with large tables. */
const py = `
import json, os, re, sys
from pathlib import Path
ROOT = Path(${JSON.stringify(ROOT)})
DUMP = Path(${JSON.stringify(DUMP)})
PACK = '2026.07-affinity-arsenal-v0.6'

def load(name):
    return json.load(open(DUMP / name))

def rows_map(sheet):
    return {r['r']: r['cells'] for r in sheet['rows']}

def write_js(rel, namespace, data, note):
    path = ROOT / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    payload = json.dumps(data, separators=(',', ':'), ensure_ascii=False)
    parts = namespace.split('.')
    body = (
        f'/* GENERATED by scripts/import-affinity-arsenal-workbook.mjs — do not edit by hand.\\n'
        f' * Source: Avian_Ascent_Master_Affinity_Ailments_and_Arsenal v0.6\\n'
        f' * {note}\\n'
        f' */\\n'
        f"(function () {{\\n"
        f"  'use strict';\\n"
        f"  var Avian = globalThis.Avian || (globalThis.Avian = {{}});\\n"
        f"  Avian.data = Avian.data || Object.create(null);\\n"
    )
    cur = 'Avian.data'
    for p in parts[2:-1]:
        body += f"  {cur}.{p} = {cur}.{p} || Object.create(null);\\n"
        cur = f'{cur}.{p}'
    body += f"  {namespace} = Object.freeze({payload});\\n}})();\\n"
    path.write_text(body)
    print('wrote', rel)

# Affinity matrix + aliases (same as Phase 1 generator)
LATIN = ['terra','aeris','tempest','solis','lunae','maris']
PLAIN = ['earth','sky','storm','day','night','water']
DISPLAY = {'terra':'Earth','aeris':'Sky','tempest':'Storm','solis':'Day','lunae':'Night','maris':'Water'}
PLAIN_TO_LATIN = dict(zip(PLAIN, LATIN))
LATIN_TO_PLAIN = dict(zip(LATIN, PLAIN))
af = rows_map(load('Affinities_and_Ailments.json'))
matrix_plain = {}
for i, att in enumerate(PLAIN):
    cells = af[5+i]
    matrix_plain[att] = {}
    for j, deff in enumerate(PLAIN):
        v = cells[1+j]
        matrix_plain[att][deff] = 'dominant' if v==1.2 else ('resisted' if v==0.8 else 'neutral')
chart = {lat: {lat2: matrix_plain[LATIN_TO_PLAIN[lat]][LATIN_TO_PLAIN[lat2]] for lat2 in LATIN} for lat in LATIN}
aliases = {}
for p,l in PLAIN_TO_LATIN.items():
    aliases[p]=l; aliases[p.title()]=l; aliases[DISPLAY[l]]=l; aliases[l]=l; aliases[l.title()]=l
    latin_names={'terra':'Terra','aeris':'Aeris','tempest':'Tempest','solis':'Solis','lunae':'Lunae','maris':'Maris'}
    aliases[latin_names[l]]=l
aligned = {
    'terra': {'base':'poison','resolved':'toxic'},
    'aeris': {'base':'delayed','resolved':None},
    'tempest': {'base':'shock','resolved':'paralysed'},
    'solis': {'base':'burn','resolved':'incinerating'},
    'lunae': {'base':'bleed','resolved':None},
    'maris': {'base':'chilled','resolved':'frozen'},
}
strong = {'terra':['tempest','solis'],'aeris':['terra','lunae'],'tempest':['aeris','maris'],'solis':['lunae','aeris'],'lunae':['tempest','maris'],'maris':['terra','solis']}
weak = {'terra':['aeris','maris'],'aeris':['tempest','solis'],'tempest':['terra','lunae'],'solis':['terra','maris'],'lunae':['solis','aeris'],'maris':['tempest','lunae']}
colors = {'terra':'#8a7860','aeris':'#6a8ae8','tempest':'#c8a820','solis':'#e85020','lunae':'#6030d0','maris':'#3a5878'}
definitions = {lat:{'name':DISPLAY[lat],'legacyName':{'terra':'Terra','aeris':'Aeris','tempest':'Tempest','solis':'Solis','lunae':'Lunae','maris':'Maris'}[lat],'theme':DISPLAY[lat],'description':f"{DISPLAY[lat]}-aligned Affinity.",'strongAgainst':strong[lat],'weakAgainst':weak[lat],'alignedStatus':aligned[lat],'color':colors[lat]} for lat in LATIN}
aspects = {'packVersion':PACK,'ids':LATIN,'displayIds':PLAIN,'displayNames':DISPLAY,'plainNames':LATIN_TO_PLAIN,'aliases':aliases,'dominantMod':1.2,'neutralMod':1,'resistedMod':0.8,'chart':chart,'alignedStatus':aligned,'themes':{k:DISPLAY[k] for k in LATIN},'definitions':definitions,'affinityIds':PLAIN}
write_js('js/data/aspects.js','Avian.data.aspects',aspects,'Affinity chart with legacy Aspect aliases.')
write_js('js/data/affinities.js','Avian.data.affinities',{'packVersion':PACK,'ids':PLAIN,'legacyIds':LATIN,'toLegacy':PLAIN_TO_LATIN,'toPlain':LATIN_TO_PLAIN,'displayNames':{p:p.title() for p in PLAIN},'dominantMod':1.2,'neutralMod':1,'resistedMod':0.8,'chartPlain':matrix_plain,'aliases':aliases},'Player-facing Affinity ids + alias map.')
write_js('js/data/effect-tiers.js','Avian.data.effectTiers',{'packVersion':PACK,'buff':{'minor':6,'moderate':8,'major':12},'debuff':{'minor':6,'moderate':8,'major':12},'points':{'minor':3,'moderate':5,'major':8},'brace':{'minor':6,'moderate':8,'major':12},'stacking':{'mode':'strongestPerDirection','coreTempCapPct':20,'precisionTempCapPoints':12}},'v0.6 core 6/8/12 + point tiers 3/5/8 + Brace.')
print('core packs refreshed')
`;

const result = spawnSync('python3', ['-c', py], { cwd: ROOT, encoding: 'utf8' });
if (result.status !== 0) {
  console.error(result.stdout);
  console.error(result.stderr);
  fail('python generator failed');
}
console.log(result.stdout);

const cfgPath = path.join(ROOT, 'js/data/combat-config.js');
const cfgText = readFileSync(cfgPath, 'utf8');
if (!cfgText.includes("packVersion: '2026.07-affinity-arsenal-v0.6'")) {
  fail('js/data/combat-config.js must be hand-updated to packVersion 2026.07-affinity-arsenal-v0.6');
}

console.log('Import complete. Run: npm run verify-affinity-arsenal');
