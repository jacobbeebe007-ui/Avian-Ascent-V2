#!/usr/bin/env node
import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const source = fs.readFileSync(new URL('../js/systems/story-run-state.js', import.meta.url), 'utf8');
const values = new Map();
const context = { localStorage: { getItem: key => values.has(key) ? values.get(key) : null, setItem: (key, value) => values.set(key, String(value)), removeItem: key => values.delete(key) }, Date, JSON };
context.globalThis = context;
vm.runInNewContext(source, context, { filename: 'story-run-state.js' });
const run = context.Avian.storyRun;
assert.equal(run.load().active, false);
assert.throws(() => run.start(null), /player bird is missing/);
run.start('sparrow', 'story-blackstone');
assert.equal(run.load().playerBirdId, 'sparrow');
run.enterNode(1, 'story-blackstone', 'combat');
assert.equal(run.load().checkpoint, 'encounter');
run.winEncounter(false); run.winEncounter(false);
assert.equal(run.load().encountersCompleted, 1, 'combat completion is idempotent');
run.collectReward({ id: 'gear-a', name: 'Tail Wand', equipmentItemId: 'gear-a' });
run.collectReward({ id: 'gear-a', name: 'Tail Wand', equipmentItemId: 'gear-a' });
assert.equal(run.load().rewardsEarned.length, 1, 'reward cannot be granted twice');
assert.deepEqual(Array.from(run.load().runInventory), ['gear-a']);
run.enterNode(5, 'story-blackstone', 'shop'); run.visitShop(5); run.visitShop(5);
assert.deepEqual(Array.from(run.load().shopsVisited), ['5']);
run.enterNode(23, 'story-blackstone', 'combat'); run.winEncounter(true);
assert.equal(run.load().bossDefeated, true);
const result = run.complete({ currencyEarned: 120 });
assert.equal(result.currencyEarned, 120);
assert.equal(run.load().active, false, 'temporary state clears');
assert.equal(JSON.parse(values.get(run.COMPLETIONS_KEY)).length, 1, 'completion remains');
console.log('[vertical-slice] OK — start, encounters, reward, shop, boss, completion, reset');
